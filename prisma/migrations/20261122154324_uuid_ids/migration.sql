-- Ids become native PostgreSQL UUIDs.
--
-- Existing ids (cuid) are converted deterministically so that every foreign
-- key keeps matching without join tables: the URL namespace of uuid_generate_v5
-- (6ba7b811-9dad-11d1-80b4-00c04fd430c8) with the old id as name. A value that
-- already is a UUID is kept as is.
--
-- Rules that store an old id (an external system that saved the OIDC `sub`,
-- for example) can compute the new id the same way:
--   uuid_generate_v5('6ba7b811-9dad-11d1-80b4-00c04fd430c8', '<old id>')

